PRODUCT_BUTTONS = {"💊 Өнім туралы ақпарат", "💊 Информация о продукте"}


@router.message(F.text.in_(PRODUCT_BUTTONS))
async def show_products_menu(message: Message, lang: str):
    title = PRODUCTS_TITLE_KK if lang == "kk" else PRODUCTS_TITLE_RU
    await message.answer(title, reply_markup=get_products_keyboard(lang))


@router.callback_query(F.data.startswith("product_"))
async def show_product_info(callback: CallbackQuery, lang: str):
    info = PRODUCT_INFO.get(callback.data, {})
    text = info.get(lang, info.get("ru", "Ақпарат табылмады."))
    await callback.message.answer(text, parse_mode="Markdown")
    await callback.answer()
